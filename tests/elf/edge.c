/* Edge cases for the symbol reader, built with DWARF 3 as armcc emits it (see build.sh).
   chain.h is generated by build.sh: 300 structs n0..n299, each pointing to the next. */
#include "chain.h"

/* A bit field that crosses its 4-byte storage unit: DWARF 3 gives it a negative
   DW_AT_bit_offset. */
struct __attribute__((packed)) cross { unsigned char a : 7; unsigned int b : 30; unsigned char c; };
struct cross crossing = { 0x55, 0x2AAAAAAA, 0x77 };

/* Mutually referencing structs: the typedef pair_t is still being read when pair_t[3] and
   const pair_t are met inside struct holder. */
struct holder;
typedef struct pair { struct holder *owner; unsigned short a, b; } pair_t;
struct holder { pair_t arr[3]; const pair_t c; unsigned int tail; };
pair_t first_pair = { 0, 1, 2 };
struct holder held = { { { 0, 1, 2 }, { 0, 3, 4 }, { 0, 5, 6 } }, { 0, 7, 8 }, 0xCAFEF00D };

/* A long chain of structs linked by pointers. */
struct n0 chain0 = { 0, 7 };

int main(void) { return held.arr[0].a + crossing.c + chain0.v; }
